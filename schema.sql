-- 1. 기존 테이블이 존재할 경우 정리 (새로 생성 시 필요할 때만 주석 해제)
-- DROP TABLE IF EXISTS cafe_orders;

-- 2. 카페 주문 테이블 생성
CREATE TABLE IF NOT EXISTS cafe_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 주문 번호 (자동 증가 고유 ID)
  name TEXT NOT NULL,                                     -- 주문자 이름 (필수)
  phone TEXT,                                             -- 전화번호
  drink TEXT NOT NULL,                                    -- 음료 이름 (예: 카페라떼)
  size VARCHAR(10) NOT NULL DEFAULT 'M',                  -- 사이즈 (S, M, L)
  options TEXT[],                                         -- 추가 옵션 배열 (예: ['샷 추가', '크림 추가'])
  quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),-- 주문 수량 (최소 1 이상)
  requests TEXT,                                          -- 요청사항
  total_price INTEGER NOT NULL CHECK (total_price >= 0),  -- 총 결제 금액
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL           -- 주문 접수 일시 (기본값: 현재 시간)
);

-- 테이블 설명 및 컬럼 주석 추가
COMMENT ON TABLE cafe_orders IS '바이브 카페 고객 주문 내역 테이블';
COMMENT ON COLUMN cafe_orders.id IS '주문 고유 식별 번호';
COMMENT ON COLUMN cafe_orders.name IS '주문자 이름';
COMMENT ON COLUMN cafe_orders.phone IS '연락처';
COMMENT ON COLUMN cafe_orders.drink IS '주문 음료명';
COMMENT ON COLUMN cafe_orders.size IS '사이즈 (S, M, L)';
COMMENT ON COLUMN cafe_orders.options IS '추가 옵션 목록 (배열)';
COMMENT ON COLUMN cafe_orders.quantity IS '수량';
COMMENT ON COLUMN cafe_orders.requests IS '고객 요청사항';
COMMENT ON COLUMN cafe_orders.total_price IS '총 주문 금액';
COMMENT ON COLUMN cafe_orders.created_at IS '주문 생성 시간';

-- 3. Row Level Security (RLS) 활성화
-- Supabase에서는 데이터 보안을 위해 RLS 활성화를 강력히 권장합니다.
ALTER TABLE cafe_orders ENABLE ROW LEVEL SECURITY;

-- 4. 익명 사용자(웹페이지 방문 고객) 권한 정책 (Policy) 설정
-- 웹사이트에서 로그인 없이 주문을 넣고 조회/취소할 수 있도록 anon 역할에 허용합니다.

-- (1) 누구나 주문을 등록(INSERT)할 수 있도록 허용
CREATE POLICY "누구나 주문 추가 가능"
ON cafe_orders
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- (2) 누구나 주문 내역을 조회(SELECT)할 수 있도록 허용
CREATE POLICY "누구나 주문 내역 조회 가능"
ON cafe_orders
FOR SELECT
TO anon, authenticated
USING (true);

-- (3) 누구나 주문을 취소(DELETE)할 수 있도록 허용
CREATE POLICY "누구나 주문 취소 가능"
ON cafe_orders
FOR DELETE
TO anon, authenticated
USING (true);

